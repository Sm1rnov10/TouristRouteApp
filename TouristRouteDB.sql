    r.name AS route_name,
    p.name AS place_name,
    p.address,
    p.category,
    p.cost,
    rp.visit_order
FROM routes r
JOIN route_places rp ON r.id = rp.route_id
JOIN places p ON rp.place_id = p.id
ORDER BY r.id, rp.visit_order;

