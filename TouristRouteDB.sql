-- 1. Таблица туристических мест
CREATE TABLE places (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    address VARCHAR(255) NOT NULL,
    coordinates VARCHAR(100),
    category VARCHAR(100) NOT NULL,
    cost NUMERIC(10, 2) NOT NULL DEFAULT 0,
    CONSTRAINT chk_place_cost CHECK (cost >= 0)
);

-- 2. Таблица туристических маршрутов
CREATE TABLE routes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description TEXT,
    duration_minutes INTEGER NOT NULL,
    CONSTRAINT chk_route_duration CHECK (duration_minutes > 0)
);

-- 3. Связь маршрутов и мест
CREATE TABLE route_places (
    route_id BIGINT NOT NULL,
    place_id BIGINT NOT NULL,
    visit_order INTEGER NOT NULL,

    PRIMARY KEY (route_id, place_id),

    FOREIGN KEY (route_id)
        REFERENCES routes(id)
        ON DELETE CASCADE,

    FOREIGN KEY (place_id)
        REFERENCES places(id)
        ON DELETE CASCADE,

    CONSTRAINT chk_visit_order CHECK (visit_order > 0),
    CONSTRAINT uq_route_visit_order UNIQUE (route_id, visit_order)
);

